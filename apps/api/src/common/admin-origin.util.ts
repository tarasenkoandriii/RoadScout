// За прямим запитом користувача — реальний знайдений інцидент: ADMIN_ORIGIN не був заданий у
// Vercel-проєкті API, тому спрацював дефолтний фолбек 'http://localhost:3001' (поставлений
// для зручності локальної розробки) — і реальні відвідувачі задеплоєного API отримували
// редирект на власний localhost власного браузера, який або не відповідає взагалі, або (як
// сталось у користувача) випадково завантажує локальний dev-сервер, якщо той теж запущений —
// вкрай заплутана поведінка.
//
// Виправлення: fallback на localhost допустимий ЛИШЕ коли застосунок дійсно НЕ на Vercel
// (Vercel завжди виставляє власну змінну `VERCEL=1` для будь-якого деплою, включно з preview) —
// якщо ADMIN_ORIGIN не заданий САМЕ на Vercel, повертаємо null, і викликач (контролер/фільтр)
// сам вирішує коректно деградувати (не редиректити НІКУДИ, а не редиректити на щось хибне).
export function resolveAdminOrigin(): string | null {
  const configured = process.env.ADMIN_ORIGIN;
  if (configured) return configured;

  const isVercel = process.env.VERCEL === '1';
  if (isVercel) return null; // краще взагалі не редиректити, ніж редиректити на локалхост реального відвідувача

  return 'http://localhost:3001'; // безпечний дефолт лише для локальної розробки (Docker/`npm run start:dev`)
}
